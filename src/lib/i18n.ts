const dict: Record<Locale, Record<string, string>> = { en, 'pt-BR': ptBR }

/** Traduz uma chave. Em templates e adapters, lê o idioma atual (reativo). */
export function t(key: string, params: Record<string, string | number> = {}): string {
  const table = dict[locale.value]
  let s = table[key] ?? en[key] ?? key
  if (params.count === 1 && (table[`${key}_one`] ?? en[`${key}_one`])) {
    s = table[`${key}_one`] ?? en[`${key}_one`]
  }
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''))
}
